"""V2 replay engine: one explicit event sequence per session.

Session d, in order:
  1. target event (if a target is effective at d): value the book at the valuation price, size the
     parent order per asset, close the previous parent (its unfilled part is cancelled, not added),
     and reconcile the demand ledger (continued / new / withdrawn demand);
  2. liquidity gate: |fill notional at the open| <= participation x ADV (ex-ante liquidity-budget proxy);
  3. cash gate: sells first, then one proportional scale on all buys; no borrowing unless configured;
  4. final-execution floor: a fill whose final notional is below min_trade_notional is not executed;
  5. fills at the session-d open; modelled cost debited once, separately from the price;
  6. close mark.
Quantities are units of the (adjusted) price series, not physical shares.

Demand ledger (policy-independent). For each asset the true demand gap at a target event is
g = target units - held units (after unit rounding), whatever the residual policy does with it.
Outstanding demand is kept as FIFO cohorts (units, basis price, origin session). At a target event
the outstanding remainder r is compared with g: the same-signed overlap continues, any excess of g
is new demand (a new cohort valued at the sizing price of that event), any excess of r is withdrawn
(newest cohorts first). Fills serve cohorts oldest first and are valued at the cohort's basis price.
A fill beyond outstanding demand (possible only under the legacy additive diagnostic) is overshoot
and is recorded separately. Hence, at basis prices:
    originated = executed + withdrawn + outstanding at end,
and completion = executed / originated lies in [0, 1] by construction, with no clipping.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from .config import ScenarioConfig, information_class
from .data import Features, Market, build_features, check_features, session_range
from .errors import RunStateError, ScenarioInputError
from .strategies import build_targets

EPS_UNITS = 1e-12


@dataclass
class RunResult:
    cfg: ScenarioConfig
    dates: pd.DatetimeIndex
    tickers: list
    daily: pd.DataFrame
    positions: np.ndarray
    target_eff: np.ndarray
    orders: pd.DataFrame
    parents: pd.DataFrame
    info: dict = field(default_factory=dict)
    demand: pd.DataFrame = field(default_factory=pd.DataFrame)


def _cost(cfg: ScenarioConfig, notional: np.ndarray, adv: np.ndarray, vol: np.ndarray) -> np.ndarray:
    """Dollar cost per asset for non-negative fill notionals. Fails closed on unusable liquidity inputs."""
    c = cfg.cost
    out = np.zeros_like(notional)
    traded = notional > 0
    if not c.enabled or not traded.any():
        return out
    a, v = adv[traded], vol[traded]
    if not (np.all(np.isfinite(a)) and np.all(a > 0) and np.all(np.isfinite(v)) and np.all(v > 0)):
        raise ScenarioInputError("missing or invalid ADV/volatility for a traded asset; refusing to cost the fill")
    x = np.minimum(notional[traded] / a, 1.0)
    bps = c.fees_bps + c.half_spread_bps + c.a_bps * x ** c.b * (v / c.vol_ref) ** c.c
    out[traded] = notional[traded] * bps / 1e4
    if not np.all(np.isfinite(out)):
        raise ScenarioInputError("cost model produced a non-finite value")
    return out


def _check_prices(p: np.ndarray, mask: np.ndarray, what: str):
    if mask.any() and not (np.all(np.isfinite(p[mask])) and np.all(p[mask] > 0)):
        raise ScenarioInputError(f"missing or non-positive {what} price for an asset that must be priced")


def run(mkt: Market, cfg: ScenarioConfig, targets: dict | None = None, tape=None, feats: Features | None = None,
        production: bool = False) -> RunResult:
    """`production=True` is the strict boundary used for historical work: complete raw inputs, features verified by
    recomputation, and targets generated by the registered strategy. Everything here runs before the first session."""
    mkt.validate()
    start, end = session_range(mkt, cfg)
    mkt.validate_domain(end, strict=production)
    if feats is None:
        feats = build_features(mkt, cfg.features, cfg.adv_estimator)
    binding = check_features(mkt, cfg, feats, production)
    targets_source = "strategy" if targets is None and tape is None else "supplied"
    if production and targets_source != "strategy":
        raise ScenarioInputError("production replay generates targets from the registered strategy; supplied targets are a synthetic route")
    if targets is None:
        targets = build_targets(mkt, cfg, start, end, tape)
    for k in targets:
        if isinstance(k, bool) or not isinstance(k, (int, np.integer)) or not (start <= k < end):
            raise ScenarioInputError(f"target session {k!r} is outside the evaluation range [{start}, {end})")
    N = len(mkt.tickers)
    integer = cfg.units == "integer"
    floor_ = cfg.min_trade_notional
    tol = 1e-9 * max(1.0, cfg.initial_cash)                 # scale-aware dollar tolerance
    h = np.zeros(N)
    cash = float(cfg.initial_cash)
    rem = np.zeros(N)                                       # signed unfilled units of the open parent (policy state)
    pid = np.full(N, -1)
    dem_rem = np.zeros(N)                                   # signed outstanding true demand (policy-independent)
    cohorts = [[] for _ in range(N)]                        # FIFO of [units, basis price, origin session]
    parents, orders, daily, demand = [], [], [], []
    positions = np.zeros((end - start, N))
    target_eff = np.full((end - start, N), np.nan)
    cur_target = None
    idx = np.arange(N)

    def drow(d, i, event, units, basis, origin):
        demand.append(dict(session=d, ticker=mkt.tickers[i], event=event, units=float(units), basis_price=float(basis),
                           value=float(units * basis), origin_session=int(origin)))

    def close_parent(i, d, mark, reason):
        if not (np.isfinite(mark) and mark > 0):
            raise ScenarioInputError(f"missing or non-positive price needed to mark the unfilled part of an order ({reason}, {mkt.tickers[i]}, session {d})")
        p = parents[pid[i]]
        p.update(close_session=d, p_H=float(mark), unfilled=float(rem[i]), close_reason=reason)
        pid[i] = -1

    for d in range(start, end):
        O, C = mkt.open[d], mkt.close[d]
        tgt = targets.get(d)
        nav_pre = np.nan
        _check_prices(O, h != 0, "open")
        nav_open = cash + float(h @ np.where(h != 0, O, 0.0))        # opening pre-trade NAV (reporting denominator)
        if tgt is not None:
            tgt = np.asarray(tgt, float)
            if tgt.shape != (N,) or not np.all(np.isfinite(tgt)) or np.any(tgt < 0) or tgt.sum() > 1 + 1e-12:
                raise ScenarioInputError("invalid target weights")
            if cfg.valuation == "prior_close":
                Pval = Psize = mkt.close[d - 1]
            elif cfg.valuation == "open":
                Pval = Psize = O
            else:                                           # same_close: legacy, violates the contract
                Pval, Psize = C, O
            _check_prices(Pval, h != 0, "valuation")
            _check_prices(Psize, tgt > 0, "sizing")
            nav_pre = cash + float(h @ np.where(h != 0, Pval, 0.0))
            desired = np.zeros(N)
            pos_t = tgt > 0
            desired[pos_t] = tgt[pos_t] * nav_pre / Psize[pos_t]
            g = desired - h                                 # true demand gap
            if integer:
                g = np.trunc(g)
            g[np.abs(g) < EPS_UNITS] = 0.0
            prev_unfilled = rem.copy()
            for i in np.nonzero(pid >= 0)[0]:
                close_parent(i, d, Psize[i], "replaced")
            q = g + prev_unfilled if cfg.residual_policy == "legacy_additive" else g.copy()   # additive: diagnostic only
            involved = (g != 0) | (dem_rem != 0)
            _check_prices(Psize, involved, "sizing")
            new_u, cont_u, wd_u = np.zeros(N), np.zeros(N), np.zeros(N)
            for i in np.nonzero(involved)[0]:
                r = dem_rem[i]
                keep = min(abs(g[i]), abs(r)) if r * g[i] > 0 else 0.0
                w = abs(r) - keep
                while w > EPS_UNITS and cohorts[i]:         # withdraw newest demand first
                    c = cohorts[i][-1]
                    take = min(c[0], w)
                    drow(d, i, "withdrawn", take, c[1], c[2])
                    c[0] -= take; w -= take; wd_u[i] += take
                    if c[0] <= EPS_UNITS:
                        cohorts[i].pop()
                if keep <= EPS_UNITS:
                    cohorts[i].clear()
                n = abs(g[i]) - keep
                if n > EPS_UNITS:
                    cohorts[i].append([n, float(Psize[i]), d])
                    drow(d, i, "originated", n, Psize[i], d)
                    new_u[i] = n
                cont_u[i] = keep
                dem_rem[i] = g[i]
            rem = q.copy()
            for i in np.nonzero((q != 0) | (g != 0))[0]:
                same = prev_unfilled[i] * q[i] > 0
                pid[i] = len(parents)
                parents.append(dict(parent_id=pid[i], ticker=mkt.tickers[i], open_session=d, q=float(q[i]), p_D=float(Psize[i]),
                                    p_A=float(O[i]), filled=0.0, fill_value=0.0, cost=0.0, last_fill_session=-1,
                                    reissued=float(min(abs(q[i]), abs(prev_unfilled[i]))) if same else 0.0,
                                    close_session=-1, p_H=np.nan, unfilled=np.nan, close_reason="",
                                    demand_gap=float(g[i]), demand_new=float(new_u[i]), demand_continued=float(cont_u[i]),
                                    demand_withdrawn=float(wd_u[i]), demand_new_value=float(new_u[i] * Psize[i]),
                                    demand_executed_units=0.0, demand_executed_value=0.0, overshoot_units=0.0, overshoot_value=0.0))
            cur_target = tgt
        cost_day = gross = 0.0
        act = np.nonzero(rem)[0]
        if act.size:
            _check_prices(O, rem != 0, "open")
            intent = rem.copy()
            cap_units = np.full(N, np.inf)
            adv, vol = feats.adv[d], feats.vol[d]
            if cfg.cap_enabled:
                if not (np.all(np.isfinite(adv[act])) and np.all(adv[act] > 0)):
                    raise ScenarioInputError("missing or invalid ADV with the liquidity limit enabled; refusing to trade unconstrained")
                cap_dollars = cfg.max_participation * adv
                if cfg.max_trade_notional is not None:
                    cap_dollars = np.minimum(cap_dollars, cfg.max_trade_notional)
                cap_units[act] = cap_dollars[act] / O[act]
            elif cfg.max_trade_notional is not None:
                cap_units[act] = cfg.max_trade_notional / O[act]
            liq = np.clip(intent, -cap_units, cap_units)
            liq = np.maximum(liq, -h)                       # never sell more than is held
            if integer:
                liq = np.trunc(liq)
            elig = liq.copy()
            Oz = np.where(rem != 0, O, 0.0)
            small = (np.abs(elig) * Oz < floor_) & (elig != 0)
            elig[small] = 0.0
            filled = np.zeros(N)
            costs = np.zeros(N)
            floored = np.zeros(N, bool)                     # dropped by the final-execution floor after cash scaling
            if cfg.cash_rule == "sells_first_proportional":
                sells = np.minimum(elig, 0.0)
                sn = -sells * Oz
                sc = _cost(cfg, sn, adv, vol)
                cash += sn.sum() - sc.sum()
                h = h + sells
                buys = np.maximum(elig, 0.0)

                def need(a):
                    b = a * buys
                    if integer:
                        b = np.floor(b + 1e-12)
                    n = b * Oz
                    c = _cost(cfg, n, adv, vol)
                    return n.sum() + c.sum(), b, c

                total, b, bc = need(1.0)
                if not cfg.allow_borrowing and total > cash:
                    lo, hi = 0.0, 1.0
                    for _ in range(64):
                        mid = 0.5 * (lo + hi)
                        if need(mid)[0] <= cash:
                            lo = mid
                        else:
                            hi = mid
                    total, b, bc = need(lo)
                # final-execution floor: a scaled buy below the minimum is not executed; freed cash is not reallocated
                floored = (b > 0) & (b * Oz < floor_ * (1 - 1e-12))
                if floored.any():
                    b = np.where(floored, 0.0, b)
                    bc = _cost(cfg, b * Oz, adv, vol)
                    total = float((b * Oz).sum() + bc.sum())
                cash -= total
                h = h + b
                filled, costs = sells + b, sc + bc
            else:                                           # legacy_sequential: ticker order, interleaved (diagnostic)
                for i in act:
                    e = elig[i]
                    if e == 0:
                        continue
                    one = np.zeros(N); one[i] = abs(e) * O[i]
                    c = _cost(cfg, one, adv, vol)[i]
                    if e > 0 and not cfg.allow_borrowing and cash < one[i] + c:
                        u = max(cash - c, 0.0) / O[i]
                        u = np.floor(u) if integer else u
                        if u <= 0:
                            continue
                        if u * O[i] < floor_ * (1 - 1e-12):
                            floored[i] = True
                            continue
                        e = u
                        one[i] = u * O[i]
                        c = _cost(cfg, one, adv, vol)[i]
                    cash -= e * O[i] + c
                    h[i] += e
                    filled[i], costs[i] = e, c
            rem = rem - filled
            rem[np.abs(rem) * np.where(rem != 0, O, 0.0) < 1e-12] = 0.0
            cost_day = float(costs.sum())
            gross = float((np.abs(filled) * Oz).sum())
            for i in act:
                p = parents[pid[i]]
                if filled[i] != 0:
                    p["filled"] += float(filled[i]); p["fill_value"] += float(filled[i] * O[i]); p["cost"] += float(costs[i])
                    p["last_fill_session"] = d
                    r = dem_rem[i]
                    served = min(abs(filled[i]), abs(r)) if r * filled[i] > 0 else 0.0
                    over = abs(filled[i]) - served
                    left = served
                    while left > EPS_UNITS and cohorts[i]:  # serve oldest demand first, valued at its basis
                        c = cohorts[i][0]
                        take = min(c[0], left)
                        drow(d, i, "executed", take, c[1], c[2])
                        p["demand_executed_units"] += take; p["demand_executed_value"] += take * c[1]
                        c[0] -= take; left -= take
                        if c[0] <= EPS_UNITS:
                            cohorts[i].pop(0)
                    dem_rem[i] = r - np.sign(r) * served if served else r
                    if abs(dem_rem[i]) <= EPS_UNITS:
                        dem_rem[i] = 0.0; cohorts[i].clear()
                    if over > 1e-9:
                        drow(d, i, "overshoot", over, O[i], d)
                        p["overshoot_units"] += over; p["overshoot_value"] += over * O[i]
                reasons = []
                if abs(liq[i]) < abs(intent[i]) - 1e-12:
                    reasons.append("liquidity")
                if small[i] or floored[i]:
                    reasons.append("min_trade")
                if abs(filled[i]) < abs(elig[i]) - 1e-12:
                    reasons.append("cash")
                notional = abs(filled[i]) * O[i]
                orders.append(dict(session=d, date=mkt.dates[d], ticker=mkt.tickers[i], parent_id=int(pid[i]), intent_units=float(intent[i]),
                                   liq_eligible_units=float(liq[i]), cash_eligible_units=float(elig[i]), filled_units=float(filled[i]),
                                   fill_price=float(O[i]), notional=float(filled[i] * O[i]), cost=float(costs[i]),
                                   cap_units=float(cap_units[i]), participation=float(notional / adv[i]) if np.isfinite(adv[i]) and adv[i] > 0 else np.nan,
                                   limited_by="+".join(reasons)))
            if cfg.residual_policy != "cancel":
                for i in act:
                    if rem[i] == 0 and pid[i] >= 0:
                        close_parent(i, d, O[i], "completed")
        if cfg.residual_policy == "cancel":                 # every open order is cancelled at the close, traded or not
            for i in np.nonzero(pid >= 0)[0]:
                close_parent(i, d, C[i], "cancelled_eod")
            rem[:] = 0.0
        _check_prices(C, h != 0, "close")
        hv = float(h @ np.where(h != 0, C, 0.0))
        nav = cash + hv
        if not (np.isfinite(cash) and np.isfinite(nav) and nav > 0):
            raise RunStateError(f"non-finite or non-positive cash/NAV at session {d}")
        if not cfg.allow_borrowing and cash < -tol:
            raise RunStateError(f"negative cash {cash} at session {d}")
        if np.any(h < -1e-9):
            raise RunStateError(f"short position at session {d}")
        k = d - start
        positions[k] = h
        if cur_target is not None:
            target_eff[k] = cur_target
        daily.append(dict(date=mkt.dates[d], nav=nav, cash=cash, holdings_value=hv, cost=cost_day, gross_traded=gross,
                          nav_pretrade=nav_pre, target_event=tgt is not None, nav_open=nav_open))
    last = end - 1
    for i in np.nonzero(pid >= 0)[0]:
        close_parent(i, last, mkt.close[last][i], "end_of_sample")
    for i in idx:
        for c in cohorts[i]:
            if c[0] > EPS_UNITS:
                drow(last, i, "outstanding_end", c[0], c[1], c[2])
    ocols = ["session", "date", "ticker", "parent_id", "intent_units", "liq_eligible_units", "cash_eligible_units", "filled_units",
             "fill_price", "notional", "cost", "cap_units", "participation", "limited_by"]
    pcols = ["parent_id", "ticker", "open_session", "q", "p_D", "p_A", "filled", "fill_value", "cost", "last_fill_session", "reissued",
             "close_session", "p_H", "unfilled", "close_reason", "demand_gap", "demand_new", "demand_continued", "demand_withdrawn",
             "demand_new_value", "demand_executed_units", "demand_executed_value", "overshoot_units", "overshoot_value"]
    dcols = ["session", "ticker", "event", "units", "basis_price", "value", "origin_session"]
    return RunResult(cfg, mkt.dates[start:end], list(mkt.tickers), pd.DataFrame(daily).set_index("date"), positions, target_eff,
                     pd.DataFrame(orders, columns=ocols), pd.DataFrame(parents, columns=pcols),
                     dict(information=information_class(cfg.valuation, cfg.features), dollar_tolerance=tol, start=start, end=end,
                          features_binding=binding, features_market_id=feats.market_id, market_id=mkt.identity(),
                          feature_window=feats.window, target_sessions=sorted(int(k) for k in targets),
                          targets_source=targets_source, production=bool(production)),
                     pd.DataFrame(demand, columns=dcols))
